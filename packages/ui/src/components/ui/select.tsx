export interface SelectProps extends FieldChromeProps {
  /** Selected value (controlled). Use `""` to clear. */
  value?: string;
  /** Initial value (uncontrolled). */
  defaultValue?: string;
  /** Called when the user picks an option. */
  onValueChange?: (value: string) => void;
  /** Open state (controlled). */
  open?: boolean;
  /** Initial open state (uncontrolled). */
  defaultOpen?: boolean;
  /** Called when the dropdown opens or closes. */
  onOpenChange?: (open: boolean) => void;
  /** Text shown when nothing is selected. Keeps the label floated. */
  placeholder?: React.ReactNode;
  /** Form field name. A hidden native `<select>` is rendered inside forms. */
  name?: string;
  /** Require a value for form submission. */
  required?: boolean;
  /** Disable the whole select. */
  disabled?: boolean;
  /** Autocomplete hint for the hidden native select. */
  autoComplete?: string;
  /** Associate with a `<form>` by id. */
  form?: string;
  /** Reading direction. */
  dir?: "ltr" | "rtl";
  /** Id of the trigger (generated by default). */
  id?: string;
  /** `SelectItem`, `SelectGroup`, `SelectLabel` and `SelectSeparator` elements. */
  children?: React.ReactNode;
  /** Ref to the trigger button. */
  ref?: React.Ref<HTMLButtonElement>;
  /** Class for the trigger button. */
  triggerClassName?: string;
  /** Class for the dropdown content. */
  contentClassName?: string;
  /** Accessible name when there is no visible label. */
  "aria-label"?: string;
  /** Extra ids describing the trigger. */
  "aria-describedby"?: string;
}

/**
 * Materialize select built on Radix Select: a text-field style trigger with a floating label and
 * a portaled dropdown that flips and shifts to stay on screen, even inside modals and
 * `overflow: hidden` containers.
 */
export function Select({
  value: valueProp,
  defaultValue,
  onValueChange,
  open: openProp,
  defaultOpen,
  onOpenChange,
  placeholder,
  name,
  required,
  disabled = false,
  autoComplete,
  form,
  dir,
  id: idProp,
  label,
  helperText,
  error,
  success = false,
  prefix,
  variant = "standard",
  fullWidth = true,
  className,
  labelClassName,
  triggerClassName,
  contentClassName,
  children,
  ref,
  "aria-label": ariaLabel,
  "aria-describedby": describedByProp,
}: SelectProps): React.JSX.Element {
  const autoId = React.useId();
  const id = idProp ?? autoId;
  const [value, setValue] = useControllableState<string>({ value: valueProp, defaultValue: defaultValue ?? "", onChange: onValueChange });
  const [open, setOpen] = useControllableState<boolean>({ value: openProp, defaultValue: defaultOpen ?? false, onChange: onOpenChange });
  const [focused, setFocused] = React.useState(false);
  const invalid = hasFieldError(error);
  const hasPrefix = prefix !== undefined && prefix !== null;
  const floating = value !== "" || open || focused || placeholder !== undefined;

  return (
    <SelectPrimitive.Root
      value={value}
      onValueChange={setValue}
      open={open}
      onOpenChange={setOpen}
      name={name}
      required={required}
      disabled={disabled}
      autoComplete={autoComplete}
      form={form}
      dir={dir}
    >
      <TextFieldRoot variant={variant} fullWidth={fullWidth} className={className} data-slot="select">
        {hasPrefix ? <TextFieldPrefix variant={variant}>{prefix}</TextFieldPrefix> : null}
        <SelectPrimitive.Trigger
          ref={ref}
          id={id}
          data-slot="select-trigger"
          data-status={success && !invalid ? "success" : undefined}
          aria-label={ariaLabel}
          aria-invalid={invalid || undefined}
          aria-describedby={textFieldDescribedBy({ id, helperText, error, describedBy: describedByProp })}
          onFocus={() => setFocused(true)}
          onBlur={() => setFocused(false)}
          className={cn(
            triggerClasses(variant, hasPrefix),
            "group/trigger relative flex cursor-pointer items-center text-left disabled:cursor-default",
            "data-[state=open]:border-secondary",
            variant === "standard" ? "data-[state=open]:shadow-[0_1px_0_0_var(--secondary)]" : "data-[state=open]:shadow-[inset_0_0_0_1px_var(--secondary)]",
            "data-[placeholder]:text-muted-foreground",
            triggerClassName,
          )}
        >
          <span className="min-w-0 flex-1 truncate">
            <SelectPrimitive.Value placeholder={placeholder} />
          </span>
          <SelectPrimitive.Icon asChild>
            <ArrowDropDownIcon
              className={cn(
                "pointer-events-none absolute top-1/2 size-6 -translate-y-1/2 text-muted-foreground transition-transform duration-200 group-data-[state=open]/trigger:rotate-180 motion-reduce:transition-none",
                variant === "standard" ? "right-0" : "right-2",
              )}
            />
          </SelectPrimitive.Icon>
        </SelectPrimitive.Trigger>
        {label !== undefined && label !== null ? (
          <TextFieldLabel
            htmlFor={id}
            variant={variant}
            hasPrefix={hasPrefix}
            floating={floating}
            focusColor={false}
            className={cn(labelStateClasses({ active: focused || open, invalid, success, disabled }), labelClassName)}
          >
            {label}
          </TextFieldLabel>
        ) : null}
        <TextFieldFooter fieldId={id} variant={variant} hasPrefix={hasPrefix} helperText={helperText} error={error} />
      </TextFieldRoot>
      <SelectPrimitive.Portal>
        <SelectPrimitive.Content
          position="popper"
          sideOffset={0}
          collisionPadding={8}
          style={{ ["--label-clearance" as string]: `${label !== undefined && label !== null ? floatedLabelClearance[variant] : 0}px` }}
          data-slot="select-content"
          className={cn(
            dropdownContentClasses,
            "max-h-[min(var(--radix-select-content-available-height),22rem)] min-w-(--radix-select-trigger-width) origin-(--radix-select-content-transform-origin)",
            // Opening upward: clear the floated label instead of covering it.
            "data-[side=top]:-translate-y-(--label-clearance) data-[side=top]:max-h-[min(calc(var(--radix-select-content-available-height)-var(--label-clearance)),22rem)]",
            contentClassName,
          )}
        >
          <SelectPrimitive.ScrollUpButton className="flex h-7 cursor-default items-center justify-center text-muted-foreground">
            <ExpandLessIcon className="size-5" />
          </SelectPrimitive.ScrollUpButton>
          <SelectPrimitive.Viewport className="h-(--radix-select-trigger-height) w-full min-w-(--radix-select-trigger-width) py-2">
            {children}
          </SelectPrimitive.Viewport>
          <SelectPrimitive.ScrollDownButton className="flex h-7 cursor-default items-center justify-center text-muted-foreground">
            <ExpandMoreIcon className="size-5" />
          </SelectPrimitive.ScrollDownButton>
        </SelectPrimitive.Content>
      </SelectPrimitive.Portal>
    </SelectPrimitive.Root>
  );
}

export interface SelectItemProps extends React.ComponentProps<typeof SelectPrimitive.Item> {
  /** Leading icon. */
  icon?: React.ReactNode;
  /** Image URL shown as a 40px circle at the end of the option (Materialize `data-icon`). */
  image?: string;
  /** Alt text for `image` (decorative by default). */
  imageAlt?: string;
}

/** An option. Only the text children are shown in the trigger once selected. */
export function SelectItem({ className, children, icon, image, imageAlt = "", ...props }: SelectItemProps): React.JSX.Element {
  return (
    <SelectPrimitive.Item data-slot="select-item" className={cn(dropdownItemClasses, className)} {...props}>
      {icon !== undefined && icon !== null ? (
        <span aria-hidden="true" className="flex shrink-0 items-center text-muted-foreground">
          {icon}
        </span>
      ) : null}
      <SelectPrimitive.ItemText>{children}</SelectPrimitive.ItemText>
      {image ? <img src={image} alt={imageAlt} className="ml-auto size-10 shrink-0 rounded-full object-cover" /> : null}
    </SelectPrimitive.Item>
  );
}

/** Groups options under a `SelectLabel` (Materialize `optgroup`). */
export function SelectGroup({ className, ...props }: React.ComponentProps<typeof SelectPrimitive.Group>): React.JSX.Element {
  return (
    <SelectPrimitive.Group
      data-slot="select-group"
      className={cn("[&_[data-slot=select-item]]:pl-8", className)}
      {...props}
    />
  );
}

/** Heading of a `SelectGroup`. */
export function SelectLabel({ className, ...props }: React.ComponentProps<typeof SelectPrimitive.Label>): React.JSX.Element {
  return (
    <SelectPrimitive.Label
      data-slot="select-label"
      className={cn("px-4 pt-3 pb-1 text-sm text-muted-foreground", className)}
      {...props}
    />
  );
}

/** Divider between options or groups. */
export function SelectSeparator({ className, ...props }: React.ComponentProps<typeof SelectPrimitive.Separator>): React.JSX.Element {
  return <SelectPrimitive.Separator data-slot="select-separator" className={cn("my-1 h-px bg-border", className)} {...props} />;
}

