/**
 * Trigger classes: the text-field underline without the `peer` marker. A button never matches
 * `:placeholder-shown`, so the label's CSS float triggers would always fire; the label is floated
 * from component state instead.
 */
function triggerClasses(variant: TextFieldVariant, hasPrefix: boolean, validate = false): string {
  return textFieldControlVariants({ variant, prefix: hasPrefix, suffix: true, validate })
    .split(" ")
    .filter((token) => token !== "peer")
    .join(" ");
}

/** Label color from component state (the trigger is not a CSS `peer`). */
function labelStateClasses({
  active,
  invalid,
  success,
  disabled,
}: {
  active: boolean;
  invalid: boolean;
  success: boolean;
  disabled: boolean;
}): string {
  if (disabled) return "text-foreground/45";
  if (invalid) return "text-error";
  if (success) return "text-success";
  return active ? "text-secondary" : "";
}

const dropdownContentClasses = cn(
  "relative z-50 overflow-hidden rounded-ui bg-surface text-foreground shadow-z1 outline-none dark:ring-1 dark:ring-border",
  "data-[state=open]:animate-md-fade-in motion-reduce:animate-none",
);

const dropdownItemClasses = cn(
  "relative flex min-h-[50px] w-full cursor-pointer select-none items-center gap-4 px-4 py-3.5 text-left text-base leading-[22px] text-secondary outline-none",
  "transition-colors duration-150 motion-reduce:transition-none",
  "data-[state=checked]:bg-foreground/[0.03] aria-selected:bg-foreground/[0.03]",
  "hover:bg-foreground/8 data-[highlighted]:bg-foreground/8 data-[active=true]:bg-foreground/8",
  "data-[disabled]:cursor-default data-[disabled]:bg-transparent data-[disabled]:text-foreground/40",
  "[&_svg]:size-6 [&_svg]:shrink-0 [&_.material-icons]:text-2xl",
);

interface FieldChromeProps {
  /** Floating label. */
  label?: React.ReactNode;
  /** Helper text under the field. */
  helperText?: React.ReactNode;
  /** `true` or an error message. Sets `aria-invalid`; a message replaces the helper text and is announced. */
  error?: React.ReactNode;
  /** Show the success (valid) state. */
  success?: boolean;
  /** Leading icon (Materialize `.prefix`). */
  prefix?: React.ReactNode;
  /** Visual style: Materialize underline (`standard`) or `outlined`. */
  variant?: TextFieldVariant;
  /** Stretch to the container width. */
  fullWidth?: boolean;
  /** Class for the wrapper. */
  className?: string;
  /** Class for the `<label>`. */
  labelClassName?: string;
}

