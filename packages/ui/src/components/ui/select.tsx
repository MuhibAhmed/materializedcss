/** An option of a `MultiSelect`. */
export interface MultiSelectOption {
  /** Submitted value. */
  value: string;
  /** Visible text (also used for type-ahead). */
  label: string;
  /** Option cannot be toggled. */
  disabled?: boolean;
  /** Group heading; consecutive options with the same group are listed under it. */
  group?: string;
  /** Leading icon. */
  icon?: React.ReactNode;
}

export interface MultiSelectProps
  extends Omit<React.ComponentProps<"button">, "value" | "defaultValue" | "onChange" | "prefix" | "children" | "name" | "form">,
    FieldChromeProps {
  /** Available options. */
  options: MultiSelectOption[];
  /** Selected values (controlled). */
  value?: string[];
  /** Initial selected values (uncontrolled). */
  defaultValue?: string[];
  /** Called when the selection changes. */
  onValueChange?: (value: string[]) => void;
  /** Open state (controlled). */
  open?: boolean;
  /** Initial open state (uncontrolled). */
  defaultOpen?: boolean;
  /** Called when the list opens or closes. */
  onOpenChange?: (open: boolean) => void;
  /** Text shown when nothing is selected. Keeps the label floated. */
  placeholder?: React.ReactNode;
  /** Form field name; each selected value is submitted under it. */
  name?: string;
  /** Associate with a `<form>` by id. */
  form?: string;
  /** Require at least one value for form submission. */
  required?: boolean;
  /** How the selection is summarised in the trigger: comma-separated text (Materialize) or chips. */
  display?: "text" | "chips";
  /** Class for the trigger button. */
  triggerClassName?: string;
  /** Class for the dropdown content. */
  contentClassName?: string;
}

/**
 * Multiple select (Materialize `select[multiple]`): a listbox with filled-in checkboxes in a
 * popover, with full keyboard support and native form submission.
 */
export function MultiSelect({
  options,
  value: valueProp,
  defaultValue,
  onValueChange,
  open: openProp,
  defaultOpen,
  onOpenChange,
  placeholder,
  name,
  form,
  required,
  disabled = false,
  display = "text",
  id: idProp,
  label,
  helperText,
  error,
  success = false,
  prefix,
  variant = "standard",
  fullWidth = true,
  className,
  labelClassName,
  triggerClassName,
  contentClassName,
  ref,
  onKeyDown,
  onFocus,
  onBlur,
  "aria-describedby": describedByProp,
  ...props
}: MultiSelectProps): React.JSX.Element {
  const autoId = React.useId();
  const id = idProp ?? autoId;
  const listboxId = `${id}-listbox`;
  const labelId = `${id}-label`;
  const [value, setValue] = useControllableState<string[]>({ value: valueProp, defaultValue: defaultValue ?? [], onChange: onValueChange });
  const [open, setOpen] = useControllableState<boolean>({ value: openProp, defaultValue: defaultOpen ?? false, onChange: onOpenChange });
  const [focused, setFocused] = React.useState(false);
  const [activeIndex, setActiveIndex] = React.useState(-1);
  const listboxRef = React.useRef<HTMLDivElement>(null);
  const triggerRef = React.useRef<HTMLButtonElement | null>(null);
  const typeahead = React.useRef<{ text: string; timer: number | undefined }>({ text: "", timer: undefined });

  const invalid = hasFieldError(error);
  const hasPrefix = prefix !== undefined && prefix !== null;
  const selected = React.useMemo(() => new Set(value), [value]);
  const selectedOptions = options.filter((option) => selected.has(option.value));
  const floating = value.length > 0 || open || focused || placeholder !== undefined;
  const optionId = (index: number): string => `${id}-option-${index}`;

  const toggle = (option: MultiSelectOption | undefined): void => {
    if (!option || option.disabled) return;
    setValue((prev) => (prev.includes(option.value) ? prev.filter((v) => v !== option.value) : [...prev, option.value]));
  };

  const enabledIndexes = (): number[] =>
    options.flatMap((option, index) => (option.disabled ? [] : [index]));

  const move = (direction: 1 | -1): void => {
    const enabled = enabledIndexes();
    if (enabled.length === 0) return;
    const position = enabled.indexOf(activeIndex);
    const next =
      position === -1
        ? direction === 1
          ? enabled[0]
          : enabled[enabled.length - 1]
        : enabled[Math.min(Math.max(position + direction, 0), enabled.length - 1)];
    if (next !== undefined) setActiveIndex(next);
  };

  // Scroll the active option into view.
  React.useEffect(() => {
    if (!open || activeIndex < 0) return;
    document.getElementById(optionId(activeIndex))?.scrollIntoView({ block: "nearest" });
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [activeIndex, open]);

  const onOpenAutoFocus = (event: Event): void => {
    event.preventDefault();
    const firstSelected = options.findIndex((option) => selected.has(option.value) && !option.disabled);
    setActiveIndex(firstSelected !== -1 ? firstSelected : (enabledIndexes()[0] ?? -1));
    listboxRef.current?.focus();
  };

  const handleTypeahead = (key: string): void => {
    const state = typeahead.current;
    window.clearTimeout(state.timer);
    state.text += key.toLowerCase();
    state.timer = window.setTimeout(() => {
      state.text = "";
    }, 500);
    const repeated = state.text.split("").every((char) => char === state.text[0]);
    const search = repeated ? state.text[0] ?? "" : state.text;
    const start = repeated ? activeIndex + 1 : Math.max(activeIndex, 0);
    for (let step = 0; step < options.length; step += 1) {
      const index = (start + step) % options.length;
      const option = options[index];
      if (option && !option.disabled && option.label.toLowerCase().startsWith(search)) {
        setActiveIndex(index);
        return;
      }
    }
  };

  const onListboxKeyDown = (event: React.KeyboardEvent<HTMLDivElement>): void => {
    switch (event.key) {
      case "ArrowDown":
        event.preventDefault();
        move(1);
        break;
      case "ArrowUp":
        event.preventDefault();
        move(-1);
        break;
      case "Home":
        event.preventDefault();
        setActiveIndex(enabledIndexes()[0] ?? -1);
        break;
      case "End":
        event.preventDefault();
        setActiveIndex(enabledIndexes().at(-1) ?? -1);
        break;
      case " ":
      case "Enter":
        event.preventDefault();
        toggle(options[activeIndex]);
        break;
      case "Tab":
        event.preventDefault();
        setOpen(false);
        break;
      default:
        if (event.key.length === 1 && !event.ctrlKey && !event.metaKey && !event.altKey) {
          event.preventDefault();
          handleTypeahead(event.key);
        }
    }
  };

  const summary =
    selectedOptions.length === 0 ? (
      placeholder !== undefined ? (
        <span className="truncate text-muted-foreground">{placeholder}</span>
      ) : null
    ) : display === "chips" ? (
      <span className="flex flex-wrap gap-1.5">
        {selectedOptions.map((option) => (
          <span
            key={option.value}
            data-slot="multi-select-chip"
            className="inline-flex h-6 items-center rounded-full bg-foreground/10 px-2.5 text-[13px] font-medium text-foreground/80"
          >
            {option.label}
          </span>
        ))}
      </span>
    ) : (
      <span className="truncate">{selectedOptions.map((option) => option.label).join(", ")}</span>
    );

  let lastGroup: string | undefined;

  return (
    <Popover.Root open={open} onOpenChange={setOpen}>
      <TextFieldRoot variant={variant} fullWidth={fullWidth} className={className} data-slot="multi-select">
        {hasPrefix ? <TextFieldPrefix variant={variant}>{prefix}</TextFieldPrefix> : null}
        <Popover.Trigger asChild>
          <button
            ref={(node) => {
              triggerRef.current = node;
              if (typeof ref === "function") return ref(node);
              if (ref) ref.current = node;
              return undefined;
            }}
            type="button"
            id={id}
            role="combobox"
            disabled={disabled}
            data-slot="multi-select-trigger"
            data-status={success && !invalid ? "success" : undefined}
            aria-haspopup="listbox"
            aria-expanded={open}
            aria-controls={open ? listboxId : undefined}
            aria-invalid={invalid || undefined}
            aria-describedby={textFieldDescribedBy({ id, helperText, error, describedBy: describedByProp })}
            onKeyDown={composeEventHandlers(onKeyDown, (event: React.KeyboardEvent<HTMLButtonElement>) => {
              if (!open && (event.key === "ArrowDown" || event.key === "ArrowUp")) {
                event.preventDefault();
                setOpen(true);
              }
            })}
            onFocus={composeEventHandlers(onFocus, () => setFocused(true))}
            onBlur={composeEventHandlers(onBlur, () => setFocused(false))}
            className={cn(
              triggerClasses(variant, hasPrefix),
              "group/trigger relative flex cursor-pointer items-center text-left disabled:cursor-default",
              "data-[state=open]:border-secondary",
              variant === "standard" ? "data-[state=open]:shadow-[0_1px_0_0_var(--secondary)]" : "data-[state=open]:shadow-[inset_0_0_0_1px_var(--secondary)]",
              display === "chips" && selectedOptions.length > 0 && "h-auto min-h-12 py-2.5",
              triggerClassName,
            )}
            {...props}
          >
            <span className="min-w-0 flex-1 truncate">{summary}</span>
            <ArrowDropDownIcon
              className={cn(
                "pointer-events-none absolute top-1/2 size-6 -translate-y-1/2 text-muted-foreground transition-transform duration-200 group-data-[state=open]/trigger:rotate-180 motion-reduce:transition-none",
                variant === "standard" ? "right-0" : "right-2",
              )}
            />
          </button>
        </Popover.Trigger>
        {label !== undefined && label !== null ? (
          <TextFieldLabel
            id={labelId}
            htmlFor={id}
            variant={variant}
            hasPrefix={hasPrefix}
            floating={floating}
            focusColor={false}
            className={cn(labelStateClasses({ active: focused || open, invalid, success, disabled }), labelClassName)}
          >
            {label}
          </TextFieldLabel>
        ) : null}
        {name !== undefined ? (
          <select
            multiple
            aria-hidden="true"
            tabIndex={-1}
            name={name}
            form={form}
            required={required}
            disabled={disabled}
            value={value}
            onChange={() => undefined}
            onInvalid={() => triggerRef.current?.focus()}
            className="pointer-events-none absolute bottom-0 left-0 h-px w-px opacity-0"
          >
            {options.map((option) => (
              <option key={option.value} value={option.value}>
                {option.label}
              </option>
            ))}
          </select>
        ) : null}
        <TextFieldFooter fieldId={id} variant={variant} hasPrefix={hasPrefix} helperText={helperText} error={error} />
      </TextFieldRoot>
      <Popover.Portal>
        <Popover.Content
          role="presentation"
          align="start"
          sideOffset={0}
          collisionPadding={8}
          onOpenAutoFocus={onOpenAutoFocus}
          style={{ ["--label-clearance" as string]: `${label !== undefined && label !== null ? floatedLabelClearance[variant] : 0}px` }}
          data-slot="multi-select-content"
          className={cn(
            dropdownContentClasses,
            "flex max-h-[min(var(--radix-popover-content-available-height),22rem)] w-(--radix-popover-trigger-width) min-w-48 flex-col origin-(--radix-popover-content-transform-origin)",
            // Opening upward: clear the floated label instead of covering it.
            "data-[side=top]:-translate-y-(--label-clearance) data-[side=top]:max-h-[min(calc(var(--radix-popover-content-available-height)-var(--label-clearance)),22rem)]",
            contentClassName,
          )}
        >
          <div
            ref={listboxRef}
            id={listboxId}
            role="listbox"
            tabIndex={0}
            aria-multiselectable="true"
            aria-labelledby={label !== undefined && label !== null ? labelId : undefined}
            aria-label={label === undefined || label === null ? props["aria-label"] : undefined}
            aria-activedescendant={activeIndex >= 0 ? optionId(activeIndex) : undefined}
            onKeyDown={onListboxKeyDown}
            className="min-h-0 flex-1 overflow-y-auto py-2 outline-none"
          >
            {options.map((option, index) => {
              const isSelected = selected.has(option.value);
              const heading =
                option.group !== undefined && option.group !== lastGroup ? (
                  <div key={`group-${option.group}`} role="presentation" className="px-4 pt-3 pb-1 text-sm text-muted-foreground">
                    {option.group}
                  </div>
                ) : null;
              lastGroup = option.group;
              return (
                <React.Fragment key={option.value}>
                  {heading}
                  <div
                    id={optionId(index)}
                    role="option"
                    aria-selected={isSelected}
                    aria-disabled={option.disabled || undefined}
                    data-disabled={option.disabled ? "" : undefined}
                    data-active={index === activeIndex ? "true" : undefined}
                    data-slot="multi-select-option"
                    onMouseDown={(event) => event.preventDefault()}
                    onPointerMove={() => {
                      if (!option.disabled && index !== activeIndex) setActiveIndex(index);
                    }}
                    onClick={() => {
                      setActiveIndex(index);
                      toggle(option);
                    }}
                    className={cn(dropdownItemClasses, option.group !== undefined && "pl-8")}
                  >
                    <span
                      aria-hidden="true"
                      className={cn(
                        "relative size-[18px] shrink-0 rounded-[2px] border-2 transition-colors duration-200 motion-reduce:transition-none",
                        isSelected ? "border-secondary bg-secondary" : "border-foreground/60 bg-transparent",
                        option.disabled && "border-foreground/30",
                      )}
                    >
                      <span
                        className={cn(
                          "absolute top-px left-1 h-[10px] w-[5px] rotate-45 border-r-2 border-b-2 border-secondary-foreground transition-opacity duration-200",
                          isSelected ? "opacity-100" : "opacity-0",
                        )}
                      />
                    </span>
                    {option.icon !== undefined && option.icon !== null ? (
                      <span aria-hidden="true" className="flex shrink-0 items-center text-muted-foreground">
                        {option.icon}
                      </span>
                    ) : null}
                    <span className="min-w-0 flex-1">{option.label}</span>
                  </div>
                </React.Fragment>
              );
            })}
          </div>
        </Popover.Content>
      </Popover.Portal>
    </Popover.Root>
  );
}
