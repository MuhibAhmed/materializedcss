export interface NativeSelectProps extends Omit<React.ComponentProps<"select">, "prefix">, FieldChromeProps {
  /** Class for the `<select>`. `className` goes on the wrapper. */
  selectClassName?: string;
}

/**
 * A real `<select>` styled like the text field. Uses the platform picker, which is the best
 * choice on touch devices.
 */
export function NativeSelect({
  id: idProp,
  label,
  helperText,
  error,
  success = false,
  prefix,
  variant = "standard",
  fullWidth = true,
  className,
  labelClassName,
  selectClassName,
  disabled,
  multiple,
  style,
  "aria-describedby": describedByProp,
  "aria-invalid": ariaInvalidProp,
  children,
  ...props
}: NativeSelectProps): React.JSX.Element {
  const autoId = React.useId();
  const id = idProp ?? autoId;
  const invalid = hasFieldError(error);
  const hasPrefix = prefix !== undefined && prefix !== null;

  return (
    <TextFieldRoot variant={variant} fullWidth={fullWidth} className={className} style={style} data-slot="native-select">
      {hasPrefix ? <TextFieldPrefix variant={variant}>{prefix}</TextFieldPrefix> : null}
      <select
        id={id}
        data-slot="native-select-control"
        data-status={success && !invalid ? "success" : undefined}
        disabled={disabled}
        multiple={multiple}
        aria-invalid={invalid ? true : ariaInvalidProp}
        aria-describedby={textFieldDescribedBy({ id, helperText, error, describedBy: describedByProp })}
        className={cn(
          textFieldControlVariants({ variant, prefix: hasPrefix, suffix: !multiple }),
          "cursor-pointer disabled:cursor-default dark:[color-scheme:dark]",
          "[&_option]:bg-surface [&_option]:text-foreground [&_optgroup]:bg-surface [&_optgroup]:text-muted-foreground",
          multiple && "h-auto py-2",
          selectClassName,
        )}
        {...props}
      >
        {children}
      </select>
      {label !== undefined && label !== null ? (
        <TextFieldLabel htmlFor={id} variant={variant} hasPrefix={hasPrefix} floating className={labelClassName}>
          {label}
        </TextFieldLabel>
      ) : null}
      {!multiple ? (
        <ArrowDropDownIcon
          aria-hidden="true"
          className={cn(
            "pointer-events-none absolute size-6 text-muted-foreground",
            variant === "standard" ? "top-3 right-0" : "top-4 right-2",
          )}
        />
      ) : null}
      <TextFieldFooter fieldId={id} variant={variant} hasPrefix={hasPrefix} helperText={helperText} error={error} />
    </TextFieldRoot>
  );
}

