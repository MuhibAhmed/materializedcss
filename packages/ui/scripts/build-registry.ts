/**
 * Builds the component registry from `registry/*.json` meta files.
 *
 * Outputs:
 *  - dist/registry/index.json + dist/registry/<name>.json — bundled with the
 *    package and read by the `materializedcss` CLI.
 *  - ../../apps/docs/public/r/<name>.json — shadcn-compatible registry items, so
 *    `npx shadcn add <site>/r/button.json` works once the docs site is hosted.
 *
 * Usage: tsx scripts/build-registry.ts [--url https://example.com/r]
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { registryItemMetaSchema, type RegistryItem, type RegistryItemMeta } from "../src/cli/utils/registry-schema.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = path.join(root, "src");
const metaDir = path.join(root, "registry");
const cliOut = path.join(root, "dist", "registry");
const docsOut = path.resolve(root, "..", "..", "apps", "docs", "public", "r");

const urlFlag = process.argv.indexOf("--url");
const registryUrl = (
  (urlFlag !== -1 ? process.argv[urlFlag + 1] : undefined) ??
  process.env.MATERIALIZEDCSS_REGISTRY_URL ??
  "https://muhibahmed.github.io/materializedcss/r"
).replace(/\/$/, "");

function readMeta(): RegistryItemMeta[] {
  return readdirSync(metaDir)
    .filter((file) => file.endsWith(".json"))
    .sort()
    .map((file) => {
      const raw: unknown = JSON.parse(readFileSync(path.join(metaDir, file), "utf8"));
      const result = registryItemMetaSchema(raw);
      if (!result.ok) throw new Error(`registry/${file}: ${result.error}`);
      if (`${result.value.name}.json` !== file) throw new Error(`registry/${file}: name must match the file name`);
      return result.value;
    });
}

function build(): void {
  const items = readMeta();
  const names = new Set(items.map((item) => item.name));

  const full: RegistryItem[] = items.map((meta) => {
    for (const dep of meta.registryDependencies ?? []) {
      if (!names.has(dep)) throw new Error(`${meta.name}: unknown registry dependency "${dep}"`);
    }
    return {
      ...meta,
      files: meta.files.map((file) => {
        const abs = path.join(srcDir, file.path);
        if (!existsSync(abs)) throw new Error(`${meta.name}: missing file src/${file.path}`);
        return { ...file, content: readFileSync(abs, "utf8").replace(/\r\n/g, "\n") };
      }),
    };
  });

  mkdirSync(cliOut, { recursive: true });
  mkdirSync(docsOut, { recursive: true });

  const index = full.map(({ files, ...rest }) => ({ ...rest, files: files.map(({ content: _content, ...file }) => file) }));
  writeFileSync(path.join(cliOut, "index.json"), JSON.stringify(index, null, 2));

  for (const item of full) {
    writeFileSync(path.join(cliOut, `${item.name}.json`), JSON.stringify(item, null, 2));
    writeFileSync(path.join(docsOut, `${item.name}.json`), JSON.stringify(toShadcn(item), null, 2));
  }

  writeFileSync(
    path.join(docsOut, "registry.json"),
    JSON.stringify(
      {
        $schema: "https://ui.shadcn.com/schema/registry.json",
        name: "materializedcss",
        homepage: registryUrl.replace(/\/r$/, ""),
        items: full.map((item) => {
          const { files, ...rest } = toShadcn(item);
          return { ...rest, files: files.map(({ content: _content, ...file }) => file) };
        }),
      },
      null,
      2,
    ),
  );

  writeIndex(full);

  console.log(`registry: ${full.length} items -> dist/registry and apps/docs/public/r (${registryUrl})`);
}

interface ShadcnItem {
  $schema: string;
  name: string;
  type: string;
  title: string;
  description: string;
  dependencies?: string[];
  registryDependencies?: string[];
  categories?: string[];
  files: Array<{ path: string; type: string; target?: string; content: string }>;
}

/** Regenerate src/index.ts so every registry module is exported from the package root. */
function writeIndex(items: RegistryItem[]): void {
  const order: Record<string, number> = { "registry:lib": 0, "registry:hook": 1, "registry:ui": 2 };
  const modules = items
    .flatMap((item) => item.files)
    .filter((file) => file.type in order && /\.tsx?$/.test(file.path))
    .sort((a, b) => (order[a.type] ?? 9) - (order[b.type] ?? 9) || a.path.localeCompare(b.path))
    .map((file) => `export * from "./${file.path.replace(/\.tsx?$/, "")}.js";`);
  const lines = ["// Generated by scripts/build-registry.ts. Do not edit.", ...new Set(modules), 'export * from "./lib/palette.js";', ""];
  writeFileSync(path.join(srcDir, "index.ts"), lines.join("\n"));
}

function toShadcn(item: RegistryItem): ShadcnItem {
  return {
    $schema: "https://ui.shadcn.com/schema/registry-item.json",
    name: item.name,
    type: item.type,
    title: item.title,
    description: item.description,
    ...(item.dependencies?.length ? { dependencies: item.dependencies } : {}),
    ...(item.registryDependencies?.length
      ? { registryDependencies: item.registryDependencies.map((dep) => `${registryUrl}/${dep}.json`) }
      : {}),
    ...(item.category ? { categories: [item.category.toLowerCase()] } : {}),
    files: item.files.map((file) => ({
      path: `registry/materializedcss/${file.path}`,
      type: file.type,
      ...(file.target ? { target: file.target } : {}),
      content: file.content,
    })),
  };
}

build();
